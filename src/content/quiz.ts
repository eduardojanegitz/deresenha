/**
 * Segunda leva de perguntas do Quiz Relâmpago. Cada linha: pergunta e alternativas, com a
 * CORRETA primeiro (no jogo a ordem é embaralhada). Os IDs usam o sufixo "b" para não
 * colidir com a primeira leva, que fica em ./library.ts.
 */
const base = { status: "published" as const, lang: "pt-BR" as const };
