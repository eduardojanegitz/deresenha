const base = { status: "published" as const, lang: "pt-BR" as const };
const nota = (kind: NotaChallenge["kind"], theme: string, texts: string[], difficulty: Difficulty = "medio"): NotaChallenge[] =>
  texts.map((text, i) => ({ ...base, id: `nota-${kind}-${theme}-${i + 1}`, game: "nota", kind, theme, text, difficulty }));
const mimica = (theme: string, difficulty: Difficulty, texts: string[]): MimicaChallenge[] =>
  texts.map((text, i) => ({ ...base, id: `mimica-${theme}-${difficulty}-${i + 1}`, game: "mimica", theme, text, difficulty }));
const quem = (theme: string, names: string[], difficulty: Difficulty = "medio"): QuemChallenge[] =>
  names.map((name, i) => ({ ...base, id: `quem-${theme}-${i + 1}`, game: "quem-sou-eu", theme, name, difficulty }));

